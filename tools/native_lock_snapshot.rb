# The selected native SDK decodes its own YAML and generated environment.
require "rubygems"
require "rubygems/user_interaction"
gem "bundler", ENV.fetch("BUNDLER_PURIFIER_BUNDLER_VERSION", ">= 0")
require "bundler"
require "bundler/version" unless defined?(Bundler::VERSION)
require "bundler/definition"
require "json"
require "digest/sha2"
require "base64"
raise "expected native YAML SDK" if Bundler::Definition.respond_to?(:build)

lock_path = File.join(Bundler.root.to_s, "Gemfile.lock")
bytes = File.read(lock_path)
raise "expected native YAML lock" unless bytes.lstrip.index("---") == 0
# Definition::Locked supplies native source-index and dependency decoding;
# Runtime supplies actual installed platform selection omitted by the lock.
definition = Bundler.definition
if Bundler.respond_to?(:env_file)
  environment = Bundler.env_file
  raise "native environment missing; run native install and lock" unless environment.file?
  raise "native environment SDK mismatch" unless environment.read(100).include?("Generated by Bundler #{Bundler::VERSION}\n")
  loaded = Bundler.load
  raise "native environment unavailable" unless loaded.equal?(Bundler) && defined?(Bundler::SPECS)
  fingerprint = definition.hash
else
  # Earlier YAML SDKs expose the same generated state through Runtime.
  # Ask their native implementation for both path and fingerprint.
  runtime = Bundler.load
  raise "native environment unavailable" unless runtime.is_a?(Bundler::Runtime) &&
    runtime.respond_to?(:rb_lock_file, true) && runtime.respond_to?(:gemfile_fingerprint, true)
  environment = runtime.send(:rb_lock_file)
  raise "native environment missing; run native install and lock" unless environment.file?
  fingerprint = runtime.send(:gemfile_fingerprint)
  require environment.to_s
  raise "native environment unavailable" unless defined?(Bundler::SPECS)
end
raise "native environment SDK mismatch" unless Bundler::LOCKED_BY == Bundler::VERSION
raise "native environment fingerprint stale" unless Bundler::FINGERPRINT == fingerprint
resolved = {}
Bundler::SPECS.each { |spec| resolved[spec.name] = spec }
raise "native environment selections stale" unless resolved.keys.sort == definition.actual_dependencies.map { |dep| dep.name }.sort
sources = definition.sources
parsed = { "gemSources" => [], "gitSources" => [], "pathSources" => [],
           "checksums" => {}, "bundledWith" => nil, "rubyVersion" => nil }
source_nodes = {}
sources.each_with_index do |source, index|
  kind = source.class.name.split("::").last
  options = source.options
  case kind
  when "Rubygems"
    node = { "fields" => { "remote" => source.uri.to_s }, "remotes" => [source.uri.to_s], "specs" => [] }
    parsed["gemSources"] << node
  when "Git"
    # This YAML SDK persists the resolved commit as `ref`, unlike the
    # later text format's `revision`. Observe the locked value directly.
    revision = options["revision"] || options.fetch("ref")
    raise "native Git lock has no resolved commit" unless revision =~ /\A[0-9a-f]{40}([0-9a-f]{24})?\z/
    fields = { "remote" => options.fetch("uri"), "revision" => revision }
    ["branch", "ref", "tag", "glob", "submodules"].each { |key| fields[key] = options[key].to_s if options.key?(key) }
    node = { "fields" => fields, "remotes" => [fields["remote"]], "specs" => [] }
    parsed["gitSources"] << node
  when "Path"
    fields = { "remote" => options.fetch("path").to_s }
    fields["glob"] = options["glob"].to_s if options.key?("glob")
    node = { "fields" => fields, "remotes" => [fields["remote"]], "specs" => [] }
    parsed["pathSources"] << node
  else
    raise "unsupported native source #{kind}"
  end
  source_nodes[source] = node
end
implicit = nil
definition.actual_dependencies.each do |dependency|
  spec = resolved.fetch(dependency.name)
  raise "native version mismatch #{dependency.name}" unless dependency.requirement.satisfied_by?(spec.version)
  source = dependency.source
  node = source_nodes[source]
  unless node
    raise "native source not in lock" if source
    unless implicit
      remotes = sources.select { |candidate| candidate.is_a?(Bundler::Source::Rubygems) }.map { |candidate| candidate.uri.to_s }
      remotes = Gem.sources.map { |uri| uri.to_s } if remotes.empty?
      raise "native SDK has no archive source" if remotes.empty?
      implicit = { "fields" => { "remote" => remotes.last }, "remotes" => remotes, "specs" => [] }
      parsed["gemSources"] << implicit
    end
    node = implicit
  end
  version = spec.version.to_s
  version += "-#{spec.platform}" unless spec.platform.to_s == "ruby"
  node["specs"] << { "name" => spec.name, "version" => version }
end
["gemSources", "gitSources", "pathSources"].each do |key|
  parsed[key].each { |source| source["specs"].sort! { |a,b| a["name"] <=> b["name"] } }
end
snapshot = {
  "format" => "bundler-yaml",
  "nativeHash" => "sha256-" + Base64.encode64(Digest::SHA256.digest(bytes)).delete("\n"),
  "observed" => { "ruby" => RUBY_VERSION, "patchlevel" => (defined?(RUBY_PATCHLEVEL) ? RUBY_PATCHLEVEL : nil), "rubygems" => Gem::VERSION,
                    "bundler" => Bundler::VERSION, "platform" => Gem::Platform.local.to_s },
  "parsed" => parsed
}
puts JSON.generate(snapshot)
